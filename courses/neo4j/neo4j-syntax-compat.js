(() => {
  /* The shared lesson.js highlighter understands SQL/Cypher, text, YAML and a
     generic highlighter for Python/Java/JavaScript/Bash. Neo4j lessons also use
     PowerShell, JSON, INI and XML labels. Normalize only those labels before
     lesson.js runs, while preserving the visible code title and language-* class. */
  const aliases = {
    powershell: 'generic',
    pwsh: 'generic',
    json: 'generic',
    xml: 'generic',
    ini: 'text'
  };

  document.querySelectorAll('[data-code-block]').forEach(block => {
    const current = String(block.dataset.language || '').trim().toLowerCase();
    if (aliases[current]) block.dataset.language = aliases[current];
  });


  /* Normalize code blocks that were serialized with newline text nodes between
     direct .code-line spans. The CSS counterpart removes only that formatting
     whitespace; it does not delete code content or intentional empty lines. */
  document.querySelectorAll('.code-window code').forEach(code => {
    const hasDirectCodeLines = [...code.children].some(child =>
      child.classList?.contains('code-line')
    );
    if (hasDirectCodeLines) code.classList.add('neo4j-line-span-code');
  });

  /* Give two-column tables a stable first-column proportion. This is done at
     runtime so no table data or markup has to be rewritten. */
  document.querySelectorAll('table.data-table').forEach(table => {
    const columnCounts = [...table.rows]
      .map(row => row.cells.length)
      .filter(Boolean);
    if (columnCounts.length && Math.max(...columnCounts) === 2) {
      table.classList.add('neo4j-two-column-table');
    }
  });

  /* Chapters 23-27 were generated by a later batch that lost the numbered H2
     convention used by the main body of the course. Number topical H2 headings
     before lesson.js builds "On this page", while keeping the shared template
     headings (Learning outcomes, production judgment, summary, references)
     intentionally unnumbered. Chapter 1-2 retain their accepted introductory
     style. */
  const chapterMatch = location.pathname.match(/\/Chapter(\d{2})\/Lesson\d+\.html$/i);
  const chapterNumber = chapterMatch ? Number(chapterMatch[1]) : NaN;
  if (chapterNumber >= 23 && chapterNumber <= 27) {
    let sectionNumber = 0;
    document.querySelectorAll('.lesson-content h2').forEach(heading => {
      const text = (heading.textContent || '').trim();
      const isTemplateHeading =
        /^Learning outcomes$/i.test(text) ||
        /^Summary and next step$/i.test(text) ||
        /^Authoritative references$/i.test(text) ||
        /^(?:Final\s+)?Production judgment(?:\b|\s+and\b)/i.test(text);

      if (!text || isTemplateHeading || /^\d+\.\s/.test(text)) return;
      sectionNumber += 1;
      heading.textContent = `${sectionNumber}. ${text}`;
    });
  }

})();
